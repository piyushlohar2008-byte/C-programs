# Type casting in python

a = 10
print(a)

b = "45"

# Basics type casting:
c = int(b)
print(c)   # casting string to integer value


x = str(a)      # casting integer to string
print(type(x))


num = 10
y = float(num)  # casting integer to float value
print(type(y))
print(y)


PI = 3.145798
p = int(PI)
print(type(p))  # casting float to integer value
print(p)